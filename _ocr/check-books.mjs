for (const [name, path] of books) {
  try {
    const buf = readFileSync(path);
    const data = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
    const doc = await pdfjsLib.getDocument({ data }).promise;
    let text = "";
    for (let i = 1; i <= Math.min(3, doc.numPages); i++) {
      const page = await doc.getPage(i);
      const content = await page.getTextContent();
      text += content.items.map((item) => item.str).join(" ");
    }
    const rec = text.length >= 1000 ? "طبقة نصية → استخراج مباشر" : "مسح ضوئي → Gemini OCR";
    console.log(`${name}: ${doc.numPages} صفحة, نص أول 3 صفحات = ${text.length} حرف → ${rec}`);
    await doc.destroy();
  } catch (e) {
    console.log(`${name}: خطأ - ${e.message}`);
  }
}